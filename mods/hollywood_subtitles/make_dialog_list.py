#!/usr/bin/env python3
"""
Writes src/dialog_list.h: every script in the game's scene-script bank (asset bank 06), as
(scene, script, has_text), so the mod's "Dev: Auto Play All Dialogues" option can ask the game to play
each one in turn (func_1501D348, the function the game's own triggers and the Chapters menu call).
Standard library only:

  python make_dialog_list.py ROM [--out FILE]

ROM is the US .z64 (or a ROM hack that keeps its layout). The script ids are the indices in each
scene's archive, the same ids func_1501D348 takes (it loads bank 6, entry scene, sub-entry script,
through func_1502B6BC) and the same [script.text] numbers extract_bubble_text.py writes. has_text marks
the scripts with speech-bubble text; the rest are voice-only or camera-only cutscenes. The header holds
numbers only, no game text, so it can be committed.
"""
import argparse
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import extract_bubble_text as bubbles  # noqa: E402  (the bank layout and decoders live there)


def all_scripts(rom):
    """[(scene, script, has_text)] for every non-empty script in the bank, in bank order."""
    out = []
    for scene_index, (scene, _) in enumerate(bubbles.archive(rom[bubbles.BANK_START:bubbles.BANK_END])):
        for script_index, (payload, compressed) in enumerate(bubbles.archive(scene)):
            if not payload:
                continue
            try:
                texts = bubbles.script_texts(bubbles.unpack_script(payload, compressed))
            except Exception:  # an unreadable script: still list it, as voice-only
                texts = []
            out.append((scene_index, script_index, 1 if any(texts) else 0))
    return out


def main():
    parser = argparse.ArgumentParser(description='Writes the dialogue list header for Auto Play All Dialogues.')
    parser.add_argument('rom', help='the US ROM (big-endian .z64)')
    parser.add_argument('--out', default=str(HERE / 'src' / 'dialog_list.h'), help='header to write')
    args = parser.parse_args()

    scripts = all_scripts(bubbles.load_rom(args.rom))
    if not scripts:
        sys.exit("no scripts found: is it the US ROM?")
    rows = ['    ' + ' '.join('{ 0x%02X, %2d, %d },' % s for s in scripts[i:i + 6]) for i in range(0, len(scripts), 6)]
    with_text = sum(s[2] for s in scripts)
    Path(args.out).write_text(
        '// Every script in the game\'s scene-script bank, as { scene, script, has_text }, in bank order.\n'
        '// Numbers only (no game text). Generated by make_dialog_list.py from your ROM: %d scripts, %d with\n'
        '// speech-bubble text. Dev: Auto Play All Dialogues plays each in turn through func_1501D348.\n'
        '#ifndef DIALOG_LIST_H\n#define DIALOG_LIST_H\n\n'
        'static const unsigned char dialog_list[][3] = {\n%s\n};\n'
        '#define DIALOG_COUNT ((int)(sizeof(dialog_list) / sizeof(dialog_list[0])))\n\n#endif\n'
        % (len(scripts), with_text, '\n'.join(rows)),
        encoding='utf-8')
    print('%d scripts (%d with bubble text) written to %s' % (len(scripts), with_text, args.out))


if __name__ == '__main__':
    main()
